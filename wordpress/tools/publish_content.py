def jd(d):
    y, m, dd = d.split('-')
    return f'{y}年{int(m)}月{int(dd)}日'


def score_cells(sc, total=None):
    if sc:
        l5, lm, wr, ge = sc
        tot = l5 + lm + wr + ge
        law = l5 + lm + wr
        ok = tot >= PASS['total'] and law >= PASS['law'] and ge >= PASS['general']
        gcls = 'ok' if ge >= PASS['general'] else 'ng'
        tcls = 'ok' if ok else 'ng'
        return f'<td>{l5}</td><td>{lm}</td><td>{wr}</td><td class="{gcls}">{ge}</td><td class="{tcls}">{tot}</td>', ok
    if total is not None:
        return f'<td colspan="4">内訳未記録</td><td class="{"ok" if total >= 180 else "ng"}">{total}</td>', total >= 180
    return '<td colspan="4">未記録</td><td>未記録</td>', False


