import os, sys, json, datetime
sys.path.insert(0, os.path.dirname(__file__))
from wpsess import login, nonce, BASE

s = login()
_, REST = nonce(s)
H = {'X-WP-Nonce': REST}
API = BASE + '/wp-json/wp/v2'


def api(method, path, **kw):
    r = s.request(method, API + path, headers=H, timeout=120, **kw)
    if r.status_code >= 400:
        print('ERR', method, path, r.status_code, r.text[:300]); sys.exit(1)
    return r.json()


def upsert_term(tax, name, slug, description='', parent=0):
    found = api('GET', f'/{tax}?slug={slug}&hide_empty=false')
    body = {'name': name, 'slug': slug, 'description': description}
    if tax == 'categories':
        body['parent'] = parent
    if found:
        return api('POST', f'/{tax}/{found[0]["id"]}', json=body)['id']
    return api('POST', f'/{tax}', json=body)['id']


def upsert(ptype, slug, title, content, desc, status='publish', cats=None, tags=None, parent=0, order=0, date=None):
    found = api('GET', f'/{ptype}?slug={slug}&status=any')
    body = {'slug': slug, 'title': title, 'content': content, 'status': status,
            'comment_status': 'closed', 'ping_status': 'closed',
            'meta': {'st_description': desc}}
    if ptype == 'posts':
        body['categories'] = cats or []
        body['tags'] = tags or []
        if date:
            body['date'] = date + 'T09:00:00'
    else:
        body['parent'] = parent
        body['menu_order'] = order
    if found:
        return api('POST', f'/{ptype}/{found[0]["id"]}', json=body)
    return api('POST', f'/{ptype}', json=body)


